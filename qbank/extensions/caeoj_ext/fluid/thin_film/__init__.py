def _check_parameters(cfg, p, fail):
    if 'zero_viscosity' in p and p['zero_viscosity']<p.get('infinite_viscosity',0):
        fail('$.physics.parameters','zero_viscosity >= infinite_viscosity',p,'Carreau ordering invalid.')
    if cfg['family']=='film_cavitation' and p.get('cavitation_pressure',0)<=0:
        fail('$.physics.parameters.cavitation_pressure','positive',p.get('cavitation_pressure'),'Absolute pressure required.')

def _check_boundary(cfg, p, op, data, values, problem, loc, requirements, fail, path):
    if op=='film_pressure' and cfg['family']=='film_cavitation':
        v=values('value');theta=values('fraction');pc=p['cavitation_pressure']
        if np.any(v<pc) or np.any((v>pc)&(theta!=1)):fail(path+'.data','p>=pc; full film above pc',data,'Cavitation boundary complementarity violated.')

def check(problem, errors):
    if problem.manifest.get('physics', {}).get('model') in MODELS:
        check_declaration(problem, errors, MODELS, _check_parameters, _check_boundary)

check_fluid_reduced = check
